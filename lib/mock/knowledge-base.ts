export function searchKnowledge(query: string): KnowledgeItem[] {
  const q = query.toLowerCase()
  const scored = knowledgeBase.map((item) => {
    let score = 0
    for (const kw of item.keywords) {
      if (q.includes(kw.toLowerCase())) score += 3
    }
    if (item.question.toLowerCase().includes(q)) score += 2
    if (item.answer.toLowerCase().includes(q)) score += 1
    if (item.category.includes(query)) score += 2
    return { item, score }
  })
  return scored
    .filter((s) => s.score > 0)
    .sort((a, b) => b.score - a.score)
    .slice(0, 3)
    .map((s) => s.item)
}
